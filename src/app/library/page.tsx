// src/app/library/page.tsx
import Sidebar from "@/components/Sidebar";
import Topbar from "@/components/Topbar";
import { createSupabaseServer } from "@/lib/supabase/server";
import Link from "next/link";

export default async function LibraryPage() {
    const supabase = await createSupabaseServer();

    const { data: plans, error } = await supabase
        .from("learning_plans")
        .select("id, title, created_at, status, lessons(title, is_gdpr)")
        .order("created_at", { ascending: false });

    if (error) {
        console.error(error);
    }

    return (
        <main className="min-h-screen bg-gradient-to-br from-indigo-600 via-blue-500 to-teal-400 p-6">
            <div className="mx-auto max-w-7xl bg-white rounded-3xl shadow-2xl overflow-hidden flex">

                {/* Sidebar */}
                <Sidebar />

                {/* Main Content */}
                <div className="flex-1 bg-slate-50">

                    {/*  Top Bar  */}
                    <Topbar title="Library" />

                    {/* Page Content */}
                    <div className="p-8 space-y-8">

                        {/* Header */}
                        <div>
                            <h2 className="text-xl font-semibold mb-1">
                                AI Generated Material
                            </h2>
                            <p className="text-slate-500 text-sm">
                                Review all the lesson plans and materials generated by the AI.
                                You can revisit and refine any of the generated context.
                            </p>
                        </div>

                        {/* Cards */}
                        <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
                            {plans?.length ? (
                                plans.map((plan) => (
                                    <LibraryCard key={plan.id} plan={plan} />
                                ))
                            ) : (
                                <EmptyState />
                            )}
                        </div>
                    </div>
                </div>
            </div>
        </main>
    );
}

/*--------------------------------------------------------*/
/* Components */
/*--------------------------------------------------------*/
function LibraryCard({ plan }: { plan: any }) {
    const lesson = plan.lessons?.[0];

    return (
        <div className="bg-white rounded-2xl shadow p-6 flex gap-4">

            {/* Icon */}
            <div className="w-20 h-20 rounded-xl bg-indigo-50 flex items-center justify-center text-indigo-600 font-semibold">
                AI
            </div>

            {/* Content */}
            <div className="flex-1">
                <h3 className="font-semibold text-lg">
                    {plan.title}
                </h3>

                {/* Lesson Title */}
                <p className="text-sm text-slate-500 mt-1">
                    {lesson?.title}
                </p>

                
                {/* Status + GDPR */}
                <div className="flex items-center gap-2 mt-3">
                    {lesson?.is_gdpr && (
                        <span className="text-xs px-2 py-1 rounded bg-red-100 text-red-700">
                            GDPR
                        </span>    
                    )}

                    <span className={`text-xs px-2 py-1 rounded ${
                        plan.status === "generated"
                            ? "bg-green-100 text-green-700"
                            : plan.status === "generating"
                            ? "bg-yellow-100 text-yellow-700"
                            : "bg-gray-100 text-gray-600"
                    }`}>
                        {plan.status}
                    </span>
                </div>
                
                {/* Actions */}
                <div className="flex gap-3 mt-4">
                    <Link href={`/learning-plans/${plan.id}`}>
                        <button className="px-4 py-2 rounded-lg border text-sm hover:bg-slate-100">
                            Review
                        </button>
                    </Link>

                    <button className="px-4 py-2 rounded-lg bg-indigo-600 text-white text-sm hover:bg-indigo-700">
                        Ask for More Info
                    </button>
                </div>
            </div>
        </div>
    );
}

function EmptyState() {
    return (
        <div className="col-span-full text-center py-16 text-slate-500">
            <p className="text-lg font-medium mb-2">
                No AI generated lessons found.
            </p>
            <p className="text-sm">
                Generate your first lesson plan to see it appear here.
            </p>
        </div>
    );
}